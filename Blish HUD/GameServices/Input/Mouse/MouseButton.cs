namespace Blish_HUD.Input.Mouse {
    /// <summary>
    /// Defines the bindable mouse buttons.
    /// </summary>
    public enum MouseButtons {
        /// <summary>
        /// None.
        /// </summary>
        None = 0,

        /// <summary>
        /// Mouse button 3.  The scroll wheel when clicked.
        /// </summary>
        MiddleButton = 1,

        /// <summary>
        /// The 4th mouse button. Typically the 'back button.'
        /// </summary>
        XButton1 = 2,

        /// <summary>
        /// The 5th mouse button. Typically the 'forward button.'
        /// </summary>
        XButton2 = 4,
    }
}
